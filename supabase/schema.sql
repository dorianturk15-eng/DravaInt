create or replace function public.link_worker_to_profile()
returns trigger security definer set search_path = public language plpgsql as $$
begin
  update public.workers set app_user_id = new.id, updated_at = now()
  where lower(email) = lower(new.email) and app_user_id is null;
  return new;
end;
$$;
drop trigger if exists link_worker_after_profile on public.profiles;

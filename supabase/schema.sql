for each row execute function public.link_worker_to_profile();

create or replace function public.suspend_linked_auth_user()
returns trigger security definer set search_path = public, auth language plpgsql as $$
begin
  if old.is_active is distinct from new.is_active and new.app_user_id is not null then
    update auth.users set banned_until = case when new.is_active then null else now() + interval '100 years' end where id = new.app_user_id;
  end if;
  return new;
end;
$$;
drop trigger if exists worker_suspension_auth on public.workers;
create trigger worker_suspension_auth after update of is_active on public.workers for each row execute function public.suspend_linked_auth_user();


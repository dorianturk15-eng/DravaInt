create or replace function public.audit_row_change()
returns trigger security definer set search_path = public language plpgsql as $$
begin
  insert into public.audit_logs(action,target_table,record_id,before_state,after_state)
  values (tg_op,tg_table_name,coalesce((to_jsonb(new)->>'id'),(to_jsonb(old)->>'id')),case when tg_op='INSERT' then null else to_jsonb(old) end,case when tg_op='DELETE' then null else to_jsonb(new) end);
  return coalesce(new,old);
end;
$$;


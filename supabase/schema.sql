create or replace function public.custom_access_token_hook(event jsonb)
returns jsonb stable language plpgsql as $$
declare claims jsonb; app_role text;
begin
  select role into app_role from public.profiles where id=(event->>'user_id')::uuid;
  claims := event->'claims';
  claims := jsonb_set(claims,'{app_role}',to_jsonb(coalesce(app_role,'workers')));
  return jsonb_set(event,'{claims}',claims);
end;
$$;


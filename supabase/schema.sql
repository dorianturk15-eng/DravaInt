-- LIMITATION (improvements-plan item #10, server side): this guard compares `machine` by exact
-- string and evaluates a single tstzrange per row. Routed orders carry a zero-duration parent
-- window (their real work lives in the `operations` JSONB), so this trigger neither protects nor
-- false-flags them — DB-level double-booking is effectively unenforced for routed work. A correct
-- fix requires modelling operations as rows (a job_operations table, item #13); the client-side
-- cpm.getJobConflicts() already covers routed overlaps in the meantime.
create or replace function public.validate_job_assignment()
returns trigger language plpgsql as $$
begin
  if new.deleted_at is not null or new.status = 'done' then return new; end if;
  if new.machine <> '' and exists(select 1 from public.jobs j where j.id <> coalesce(new.id,0) and j.deleted_at is null and j.status <> 'done' and j.machine = new.machine and tstzrange(j.start_time,j.end_time,'[)') && tstzrange(new.start_time,new.end_time,'[)')) then
    raise exception 'Machine % is already allocated in this time range', new.machine using errcode = 'DR001';
  end if;
  if new.operator_id is not null and exists(select 1 from public.jobs j where j.id <> coalesce(new.id,0) and j.deleted_at is null and j.status <> 'done' and j.operator_id = new.operator_id and tstzrange(j.start_time,j.end_time,'[)') && tstzrange(new.start_time,new.end_time,'[)')) then
    raise exception 'Operator is already allocated in this time range' using errcode = 'DR001';
  end if;
  return new;
end;
$$;
drop trigger if exists validate_job_assignment_trigger on public.jobs;
create constraint trigger validate_job_assignment_trigger after insert or update of machine,operator_id,start_time,end_time,status on public.jobs deferrable initially deferred for each row execute function public.validate_job_assignment();

